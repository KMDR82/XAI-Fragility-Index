"""Line numbers for the response letter, read from the compiled manuscript.

    python scripts/letter_lines.py manuscript/main.pdf response/letter_anchors.json response/letter_lines.tex

Every anchor is a pair of phrases [start, end] copied from the manuscript text. The script finds the first
occurrence of the start phrase among the numbered lines of the PDF (lineno numbers on the left margin), then
the first occurrence of the end phrase after it, and writes \\newcommand{\\L<key>}{<first>--<last>}.
Matching ignores case, punctuation and hyphenation at line ends, so the anchors survive re-wrapping.
A missing anchor stops the script, so a stale letter cannot be built silently.
"""
import json, re, subprocess, sys
from pathlib import Path


def numbered_tokens(pdf):
    txt = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], capture_output=True, text=True, check=True).stdout
    lines, prev = [], 0
    for raw in txt.splitlines():
        m = re.match(r"^\s{0,8}(\d{1,4})\s{2,}(\S.*)$", raw)
        if m and prev < int(m.group(1)) <= prev + 5:  # line numbers increase; skips axis ticks and table cells
            lines.append((int(m.group(1)), m.group(2))); prev = int(m.group(1))
    raw = [(w, ln) for ln, text in lines for w in text.split()]
    toks, i = [], 0
    while i < len(raw):
        w, ln = raw[i]
        if (w.endswith("-") and len(w) > 1 and i + 1 < len(raw) and raw[i + 1][1] != ln
                and raw[i + 1][0][:1].islower()):  # word hyphenated across a line break
            w, i = w[:-1] + raw[i + 1][0], i + 1
        n = norm(w)
        if n:
            toks.append((n, ln))
        i += 1
    return toks


def norm(w):
    return re.sub(r"[^0-9a-z]", "", w.lower())


def find(toks, phrase, start=0):
    p = [norm(w) for w in phrase.split()]
    p = [w for w in p if w]
    words = [t[0] for t in toks]
    for i in range(start, len(words) - len(p) + 1):
        if words[i:i + len(p)] == p:
            return i, i + len(p) - 1
    return None


def main(pdf, anchors, out):
    toks = numbered_tokens(pdf)
    a = json.loads(Path(anchors).read_text())
    res, missing = [], []
    for key, (s, e) in a.items():
        assert re.fullmatch(r"[A-Za-z]+", key), key
        hs = find(toks, s)
        he = find(toks, e, hs[0]) if hs else None
        if not hs or not he:
            missing.append((key, s if not hs else e)); continue
        l1, l2 = toks[hs[0]][1], toks[he[1]][1]
        res.append((key, l1, l2))
    if missing:
        for k, ph in missing:
            print(f"MISSING {k}: {ph!r}")
        sys.exit(1)
    body = "% generated by scripts/letter_lines.py from " + Path(pdf).name + "\n"
    body += "".join(f"\\newcommand{{\\L{k}}}{{{l1}--{l2}}}\n" if l1 != l2 else f"\\newcommand{{\\L{k}}}{{{l1}}}\n" for k, l1, l2 in res)
    Path(out).write_text(body)
    print(f"{len(res)} anchors -> {out}")
    for k, l1, l2 in res:
        print(f"  {k:14s} {l1}-{l2}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
